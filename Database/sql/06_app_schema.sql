-- =====================================================================================================================
-- DiaMate application schema (schema "public")                                              PostgreSQL 15+
--
-- Follows the project report: roles PATIENT / CLINICIAN / CAREGIVER (+ ADMIN = system administrator), 3NF,
-- PATIENT/DOCTOR profile tables, glucose / insulin / meal / activity logs, reminders, alerts, reports, sharing,
-- audit trail, offline sync (client_uuid + updated_at + deleted_at, last-write-wins), AI assistant history.
--
-- Conventions (so JPA/Hibernate mapping is boring):
--   * primary keys: bigint GENERATED BY DEFAULT AS IDENTITY  ->  @GeneratedValue(strategy = GenerationType.IDENTITY)
--   * enums are VARCHAR + CHECK (use @Enumerated(EnumType.STRING)); the allowed values are listed in the CHECK constraints
--   * all points in time are timestamptz (map to Instant or OffsetDateTime; set hibernate.jdbc.time_zone=UTC)
--   * glucose is always stored in mg/dL (the UI converts to mmol/L using user_settings.glucose_unit)
--   * patient-owned rows reference patient_profiles(user_id); deleting a patient cascades to his/her data
-- =====================================================================================================================
\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------------------------------------------- helpers
CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END $$;

-- BEFORE INSERT/UPDATE guard: the referenced user must have the expected role.  args: column, role
CREATE FUNCTION require_user_role() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    uid  bigint := (to_jsonb(NEW) ->> TG_ARGV[0])::bigint;
    have text;
BEGIN
    SELECT role INTO have FROM users WHERE id = uid;
    IF have IS DISTINCT FROM TG_ARGV[1] THEN
        RAISE EXCEPTION 'user % must have role % (has %)', uid, TG_ARGV[1], have USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;

-- ------------------------------------------------------------------------------------------------- identity & access
CREATE TABLE users (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 varchar(150) NOT NULL,
    password_hash         varchar(255) NOT NULL,                 -- bcrypt ($2a$/$2b$), written by the backend only
    role                  varchar(20)  NOT NULL CHECK (role IN ('PATIENT', 'CLINICIAN', 'CAREGIVER', 'ADMIN')),
    full_name             varchar(100) NOT NULL,
    phone                 varchar(30),
    is_active             boolean      NOT NULL DEFAULT true,    -- false = deactivated (soft delete); never hard-delete health data owners
    is_demo               boolean      NOT NULL DEFAULT false,   -- true for the seeded demo accounts
    email_verified        boolean      NOT NULL DEFAULT false,
    two_factor_enabled    boolean      NOT NULL DEFAULT false,
    two_factor_secret     varchar(255),                          -- TOTP secret, encrypted by the backend
    failed_login_attempts integer      NOT NULL DEFAULT 0 CHECK (failed_login_attempts >= 0),
    locked_until          timestamptz,
    last_login_at         timestamptz,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));
CREATE INDEX ix_users_role ON users (role);
COMMENT ON TABLE users IS 'Every account (patient, clinician, caregiver, admin). Role-specific data lives in the *_profiles tables.';

CREATE TABLE patient_profiles (
    user_id                 bigint PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    diabetes_type           varchar(20) NOT NULL CHECK (diabetes_type IN ('TYPE_1', 'TYPE_2', 'GESTATIONAL', 'OTHER')),
    date_of_birth           date,
    sex                     varchar(10) CHECK (sex IN ('FEMALE', 'MALE', 'OTHER')),
    height_cm               numeric(5,1) CHECK (height_cm BETWEEN 30 AND 260),
    weight_kg               numeric(5,1) CHECK (weight_kg BETWEEN 2 AND 500),
    diagnosis_year          smallint CHECK (diagnosis_year BETWEEN 1900 AND 2100),
    therapy_type            varchar(20) CHECK (therapy_type IN ('MDI', 'PUMP', 'ORAL', 'DIET', 'MIXED', 'OTHER')),
    target_min_mgdl         smallint NOT NULL DEFAULT 70,        -- time-in-range window
    target_max_mgdl         smallint NOT NULL DEFAULT 180,
    hypo_threshold_mgdl     smallint NOT NULL DEFAULT 70,        -- alert when glucose <= this  (report: <= 70)
    hyper_threshold_mgdl    smallint NOT NULL DEFAULT 180,       -- alert when glucose >= this  (report: >= 180)
    urgent_low_mgdl         smallint NOT NULL DEFAULT 54,        -- emergency alert
    urgent_high_mgdl        smallint NOT NULL DEFAULT 250,
    emergency_contact_name  varchar(100),
    emergency_contact_phone varchar(30),
    research_patient_id     varchar(30),                         -- provenance of demo patients (research.patients.patient_id)
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_patient_target_order  CHECK (target_min_mgdl < target_max_mgdl),
    CONSTRAINT ck_patient_alert_order   CHECK (urgent_low_mgdl <= hypo_threshold_mgdl AND hypo_threshold_mgdl < hyper_threshold_mgdl
                                               AND hyper_threshold_mgdl <= urgent_high_mgdl)
);
COMMENT ON TABLE patient_profiles IS 'PATIENT table of the report: one row per patient user (diabetes type, targets, alert thresholds).';

CREATE TABLE clinician_profiles (
