-- Sharing / access control: a clinician or caregiver can see a patient's data only through an ACTIVE row here.
CREATE TABLE care_relationships (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id             bigint NOT NULL REFERENCES patient_profiles (user_id) ON DELETE CASCADE,
    member_id              bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    member_role            varchar(20) NOT NULL CHECK (member_role IN ('CLINICIAN', 'CAREGIVER')),
    status                 varchar(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACTIVE', 'REVOKED', 'DECLINED')),
    can_view_glucose       boolean NOT NULL DEFAULT true,
    can_view_meals         boolean NOT NULL DEFAULT true,
    can_view_medications   boolean NOT NULL DEFAULT true,
    can_view_activity      boolean NOT NULL DEFAULT true,
    can_view_reports       boolean NOT NULL DEFAULT true,
    can_receive_alerts     boolean NOT NULL DEFAULT true,
    can_add_recommendations boolean NOT NULL DEFAULT false,      -- clinicians only in practice
    invited_by             bigint REFERENCES users (id) ON DELETE SET NULL,
    invited_at             timestamptz NOT NULL DEFAULT now(),
    responded_at           timestamptz,
    revoked_at             timestamptz,
    expires_at             timestamptz,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_care_not_self CHECK (patient_id <> member_id)
);
CREATE UNIQUE INDEX ux_care_open_pair ON care_relationships (patient_id, member_id) WHERE status IN ('PENDING', 'ACTIVE');
CREATE INDEX ix_care_member ON care_relationships (member_id, status);
CREATE INDEX ix_care_patient ON care_relationships (patient_id, status);
COMMENT ON TABLE care_relationships IS 'Patient-controlled sharing (POST /share, DELETE /revoke). Per-permission flags; see fn_can_access().';

CREATE FUNCTION care_relationship_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE have text;
BEGIN
    SELECT role INTO have FROM users WHERE id = NEW.member_id;
    IF have IS DISTINCT FROM NEW.member_role THEN
        RAISE EXCEPTION 'member % has role % but relationship says %', NEW.member_id, have, NEW.member_role USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.status = 'REVOKED' AND NEW.revoked_at IS NULL THEN NEW.revoked_at := now(); END IF;
    IF NEW.status IN ('ACTIVE', 'DECLINED') AND NEW.responded_at IS NULL THEN NEW.responded_at := now(); END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_care_guard BEFORE INSERT OR UPDATE ON care_relationships FOR EACH ROW EXECUTE FUNCTION care_relationship_guard();

