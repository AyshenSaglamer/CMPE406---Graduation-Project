#!/usr/bin/env python3
"""Turns the inline `-- comment` after each column definition in sql/06_app_schema.sql into COMMENT ON COLUMN statements,
so that the explanations live inside the database (pgAdmin shows them, the data dictionary uses them).
usage: gen_column_comments.py sql/06_app_schema.sql sql/06b_app_column_comments.sql
"""
import re, sys

src, dst = sys.argv[1], sys.argv[2]
table, out, n = None, [], 0
for line in open(src, encoding="utf-8"):
    m = re.match(r"^CREATE TABLE (\w+) \(", line)
    if m:
        table = m.group(1)
        continue
    if table and line.startswith(");"):
        table = None
        continue
    if table:
        m = re.match(r"^\s+(\w+)\s+[\w(]", line)
        c = re.search(r"--\s*(.+?)\s*$", line)
        if m and c and m.group(1).upper() not in ("CONSTRAINT", "CHECK", "PRIMARY", "UNIQUE", "FOREIGN"):
            text = c.group(1).replace("'", "''")
            out.append(f"COMMENT ON COLUMN public.{table}.{m.group(1)} IS '{text}';")
            n += 1
with open(dst, "w", encoding="utf-8") as f:
    f.write("-- Column descriptions of the application schema (generated by tools/gen_column_comments.py from the comments in 06_app_schema.sql)\n"
            "\\set ON_ERROR_STOP on\n" + "\n".join(out) + "\n")
print(n, "column comments")
