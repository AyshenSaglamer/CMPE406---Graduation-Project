package com.diamate.backend.api.dto.request;

import java.time.Instant;
import java.util.UUID;

import com.diamate.backend.entity.MealContext;

import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

/**
 * Body of POST (create) and PUT (replace) for glucose logs. Limits are the same as the CHECK constraints
 * of glucose_logs, so a bad value is a 400 here instead of a database error (500).
 */
public record GlucoseLogRequest(

        @NotNull(message = "Glucose value is required")
        @Min(value = 10, message = "Glucose value must be at least 10 mg/dL")
        @Max(value = 600, message = "Glucose value must be at most 600 mg/dL")
        Integer glucoseValue, // mg/dL

        @NotNull(message = "Measurement time is required")
        Instant measurementTime, // ISO-8601, e.g. "2026-10-05T08:30:00Z"; must not be in the future (checked in the service)

        MealContext mealContext, // optional: FASTING, BEFORE_MEAL, AFTER_MEAL, BEDTIME, EXERCISE, OTHER

        @Size(max = 1000, message = "Notes must be at most 1000 characters")
        String notes,

        EntrySource source, // optional, default MANUAL; ignored on PUT (where a log came from does not change)

        UUID clientUuid) { // optional; generated by the app so a resent request does not create a duplicate
}
