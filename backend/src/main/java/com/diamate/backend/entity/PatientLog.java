package com.diamate.backend.entity;

import java.time.Instant;
import java.util.UUID;

import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

import jakarta.persistence.Column;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;

/**
 * Columns shared by the patient log tables (glucose_logs, insulin_logs, meal_logs, activity_logs).
 * Not a table itself: each subclass is mapped to its own table.
 *
 * Soft delete: rows are never removed, deleted_at is set instead, so an offline phone can still learn that a
 * record was deleted. Each subclass has @SQLRestriction("deleted_at IS NULL"), which hides deleted rows from
 * every query Hibernate makes.
 */
@MappedSuperclass
public abstract class PatientLog {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // A plain id instead of a @ManyToOne: the logs never need the profile object, and this avoids an extra query.
    @Column(name = "patient_id", nullable = false, updatable = false)
    private Long patientId;

    @Column(columnDefinition = "text")
    private String notes;

    // Generated by the mobile app; (patient_id, client_uuid) is unique, so a resent request is recognized.
    @Column(name = "client_uuid", updatable = false)
    private UUID clientUuid;

    // Filled by the database (DEFAULT now()).
    @Generated(event = EventType.INSERT)
    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    // Filled by the database (DEFAULT now() and the trg_*_updated trigger).
    @Generated(event = { EventType.INSERT, EventType.UPDATE })
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    @Column(name = "deleted_at")
    private Instant deletedAt;

    protected PatientLog() {
        // required by JPA
    }

    protected PatientLog(long patientId, UUID clientUuid) {
        this.patientId = patientId;
        this.clientUuid = clientUuid;
    }

    public void markDeleted(Instant when) {
        this.deletedAt = when;
    }

    protected void setNotes(String notes) {
        this.notes = notes;
    }

    public Long getId() {
        return id;
    }

    public Long getPatientId() {
        return patientId;
    }

    public String getNotes() {
        return notes;
    }

    public UUID getClientUuid() {
        return clientUuid;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public Instant getDeletedAt() {
        return deletedAt;
    }
}
