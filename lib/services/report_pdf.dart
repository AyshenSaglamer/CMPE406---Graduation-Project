import 'dart:typed_data';

import 'package:flutter/services.dart' show rootBundle;
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../data/health_report.dart';

/// Builds the A4 PDF of a [HealthReport]: summary, then one table per kind
/// of log (newest first), page numbers and a short disclaimer on every page.
/// Roboto is embedded because the PDF standard fonts have no ş, ı, ğ.
Future<Uint8List> buildReportPdf(HealthReport report) async {
  final regular = pw.Font.ttf(
    await rootBundle.load('assets/fonts/Roboto-Regular.ttf'),
  );
  final bold = pw.Font.ttf(
    await rootBundle.load('assets/fonts/Roboto-Bold.ttf'),
  );

  final doc = pw.Document(
    title: 'DiaMate Health Report',
    author: report.patientName,
    creator: 'DiaMate',
  );

  const blue = PdfColor.fromInt(0xFF168AF7);
  const muted = PdfColor.fromInt(0xFF64748B);
  const line = PdfColor.fromInt(0xFFE2E8F0);

  pw.Widget heading(String text) => pw.Padding(
        padding: const pw.EdgeInsets.only(top: 16, bottom: 6),
        child: pw.Text(
          text,
          style: pw.TextStyle(font: bold, fontSize: 13, color: blue),
        ),
      );

  pw.Widget table(List<String> headers, List<List<String>> rows) {
    if (rows.isEmpty) {
      return pw.Text(
        'No entries in this period.',
        style: const pw.TextStyle(fontSize: 9, color: muted),
      );
    }

    return pw.TableHelper.fromTextArray(
      headers: headers,
      data: rows,
      headerStyle: pw.TextStyle(font: bold, fontSize: 9),
      cellStyle: const pw.TextStyle(fontSize: 9),
      headerDecoration: const pw.BoxDecoration(
        color: PdfColor.fromInt(0xFFF1F5F9),
      ),
      border: const pw.TableBorder(
        horizontalInside: pw.BorderSide(color: line, width: 0.5),
        bottom: pw.BorderSide(color: line, width: 0.5),
      ),
      cellPadding: const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 3),
      cellAlignment: pw.Alignment.centerLeft,
    );
  }

  String n(double? v, [String unit = '']) =>
      v == null ? '-' : '${formatReportNumber(v)}$unit';

  final summary = <List<String>>[
    ['Glucose readings', '${report.glucose.length}'],
    ['Average glucose', n(report.averageGlucose, ' mg/dL')],
    [
      'Lowest / highest',
      '${n(report.lowestGlucose)} / ${n(report.highestGlucose, ' mg/dL')}',
    ],
    if (report.glucose.isNotEmpty)
      [
        'Time in range (70-180 mg/dL)',
        '${report.inRangePercent.round()}% '
            '(below ${report.belowRangePercent.round()}%, '
            'above ${report.aboveRangePercent.round()}%)',
      ],
    [
      'Insulin',
      '${n(report.insulinTotal, ' units')} in ${report.insulin.length} doses',
    ],
    [
      'Meals',
      '${report.meals.length} meals, ${n(report.carbsTotal, ' g')} carbs',
    ],
    [
      'Activity',
      '${n(report.activityMinutes, ' min')} in ${report.activities.length} sessions',
    ],
  ];

  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(36),
      theme: pw.ThemeData.withFont(base: regular, bold: bold),
      header: (context) => context.pageNumber == 1
          ? pw.SizedBox()
          : pw.Padding(
              padding: const pw.EdgeInsets.only(bottom: 8),
              child: pw.Text(
                'DiaMate Health Report - ${report.patientName}',
                style: const pw.TextStyle(fontSize: 8, color: muted),
              ),
            ),
      footer: (context) => pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            'Generated by DiaMate. A record of logged data, not a medical diagnosis.',
            style: const pw.TextStyle(fontSize: 7, color: muted),
          ),
          pw.Text(
            'Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 7, color: muted),
          ),
        ],
      ),
      build: (context) => [
        pw.Text(
          'DiaMate Health Report',
          style: pw.TextStyle(font: bold, fontSize: 22, color: blue),
        ),
        pw.SizedBox(height: 6),
        pw.Text(report.patientName, style: pw.TextStyle(font: bold, fontSize: 12)),
        pw.Text(
          'Period: ${formatReportDay(report.from)} - ${formatReportDay(report.to)} '
          '(${report.days} days)',
          style: const pw.TextStyle(fontSize: 10),
        ),
        pw.Text(
          'Generated: ${formatReportTime(report.generatedAt)}',
          style: const pw.TextStyle(fontSize: 9, color: muted),
        ),
        heading('Summary'),
        pw.TableHelper.fromTextArray(
          data: summary,
          cellStyle: const pw.TextStyle(fontSize: 10),
          border: const pw.TableBorder(
            horizontalInside: pw.BorderSide(color: line, width: 0.5),
          ),
          cellPadding: const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 4),
          columnWidths: {
            0: const pw.FlexColumnWidth(2),
            1: const pw.FlexColumnWidth(3),
          },
        ),
        heading('Blood glucose'),
        table(
          ['Date / time', 'mg/dL', 'When', 'Notes'],
          [
            for (final r in report.glucose)
              [
                formatReportTime(r.dateTime),
                formatReportNumber(r.value),
                r.measurementTime,
                r.notes ?? '',
              ],
          ],
        ),
        heading('Insulin'),
        table(
          ['Date / time', 'Units', 'Type'],
          [
            for (final r in report.insulin)
              [
                formatReportTime(r.administeredAt),
                formatReportNumber(r.doseUnits),
                r.type,
              ],
          ],
        ),
        heading('Meals'),
        table(
          ['Date / time', 'Meal', 'Carbs (g)', 'Description'],
          [
            for (final r in report.meals)
              [
                formatReportTime(r.eatenAt),
                r.mealType,
                r.carbsG == null ? '' : formatReportNumber(r.carbsG!),
                r.description ?? '',
              ],
          ],
        ),
        heading('Activity'),
        table(
          ['Date / time', 'Activity', 'Minutes'],
          [
            for (final r in report.activities)
              [
                formatReportTime(r.startedAt),
                r.activityType,
                r.durationMinutes == null
                    ? ''
                    : formatReportNumber(r.durationMinutes!),
              ],
          ],
        ),
      ],
    ),
  );

  return doc.save();
}
